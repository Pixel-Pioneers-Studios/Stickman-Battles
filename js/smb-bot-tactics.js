// ============================================================
// BOT TACTICS — per-frame decisions for the stock Fighter bots
// ============================================================
// Fighter.updateAI() runs once every AI_TICK_INTERVAL (15) frames and picks
// abilities, supers and guards by dice roll. That is too slow to continue a
// combo, punish a recovery or step out of a swing, and its wander / nudge timers
// are counted in ticks, so a bot in melee range spent most of a match in the
// wander branch and never reached the code that casts Q or E at all.
//
// This layer runs every frame for bots it owns (botTacSkill > 0), while the bot
// is level with its target and within TAC_RANGE of it. It decides spacing, when
// to swing, how to continue a hit, when to guard, and which move to throw.
// Outside that range, and for everything the old brain still does well (routing,
// climbing, hazard avoidance, target choice), updateAI() is untouched.
//
// Move knowledge comes from BOT_MOVES, measured by tools/bot-move-ranges.js.
//
// Globals-based, no modules. Loaded after smb-move-scenes-defs.js; everything
// resolves at call time. Called from Fighter.update() and, as a veto on the old
// brain's random casts, from Fighter.ability() / Fighter.useSuper().

const BOT_TACTICS = {
  enabled: true,
  // Story chapters and Battle Royale were tuned against the old brain, so their
  // bots keep it unless these are switched on (or a fighter carries _botIQ).
  story: true,
  br: true,
  // How much of the layer each difficulty gets. 0 = old brain only.
  skill: { easy: 0, medium: 0.2, hard: 0.7, expert: 1 },
  // Frames between decisions: a slower bot notices an opening late and holds a
  // stale heading in between, the way a slower player does.
  think: { medium: 10, hard: 3, expert: 1 },
  // Longest pause (frames) before a bot takes a swing it could already take in
  // the open. Combos and punishes are not delayed.
  hesitate: { medium: 70, hard: 14, expert: 0 },
};

