function botTacSkill(f) {
  // Story enemies are built as Minions (see _exploreSpawnEnemy) but fight with the
  // stock brain, so the story switch has to let them through both checks.
  const storyFoe = !!(f && f._storyFoe) && BOT_TACTICS.story;
  if (!BOT_TACTICS.enabled || !f || !f.isAI || f.isBoss || (f.isMinion && !storyFoe) || f.isRemote) return 0;
  if (f.constructor !== Fighter && !storyFoe) return 0;    // Sovereign, AdaptiveAI, creatures: own brains
  if (typeof f._botIQ === 'number') return f._botIQ;
  if (typeof storyModeActive !== 'undefined' && storyModeActive && !BOT_TACTICS.story) return 0;
  if (typeof gameMode !== 'undefined' && gameMode === 'exploration' && !BOT_TACTICS.story) return 0;
  if (typeof brActive !== 'undefined' && brActive && !BOT_TACTICS.br) return 0;
  // Public Server lobbies: every browser runs its own copy of the lobby bots.
  if (typeof PubHub !== 'undefined' && PubHub && PubHub.active) return 0;
  if (f._trialStalker || f._trialMirror || f._sportsBot || f.isExploreGuard || f._brNavLock) return 0;
  if (typeof trainingChaosMode !== 'undefined' && trainingChaosMode) return 0;
  if (typeof gameMode !== 'undefined' && gameMode === 'minigames' &&
      typeof minigameType !== 'undefined' && (minigameType === 'sports' || (minigameType === 'koth' && !f._kothContested))) return 0;
  return BOT_TACTICS.skill[f.aiDiff] || 0;
}

function _btFc() { return typeof frameCount !== 'undefined' ? frameCount : 0; }

function _btReach(f, t) {
  if (!f.weapon || f.weapon.type !== 'melee' || typeof f._meleeReachDist !== 'function') return 0;
  const k = f.weaponKey + '|' + (f.drawScale || 1) + '|' + (f._wxReachMult || 1) + '|' + (t ? t.w : 0);
  if (f._btReachKey !== k) { f._btReachKey = k; f._btReachVal = f._meleeReachDist(t); }
  return f._btReachVal;
}

function _btGroundAt(x, footY) {
  const pls = (typeof currentArena !== 'undefined' && currentArena && currentArena.platforms) || [];
  for (const pl of pls) {
    if (pl.isFloorDisabled) continue;
    if (x > pl.x + 6 && x < pl.x + pl.w - 6 && pl.y >= footY - 10) return true;
  }
  return false;
}

// Frames until `kind` ('q' | 'e') would land on t from here. -1 = it will not
// (out of band, wrong level, or it would carry the user off the stage).
// null = no data for this weapon, so no opinion.
function botMoveTime(f, kind, t) {
  const row = BOT_MOVES[f.weaponKey];
  if (!row || !t) return null;
  const d = Math.abs(t.cx() - f.cx());
  const rule = BOT_MOVE_RULES[f.weaponKey + ':' + kind];
  if (rule) {
    const r = rule(f, t, d);
    if (r === true) return 0;
    if (r === false) return -1;
  }
  const m = row[kind];
  if (!m) return -1;
  if (Math.abs((f.y + f.h) - (t.y + t.h)) > 70) return -1;
  if (d < m[0] - 10 || d > m[1] * 0.92) return -1;
  if (Math.abs(m[4]) >= 60) {
    // Walls stop a travelling move; an open ledge does not.
    const dir = t.cx() >= f.cx() ? 1 : -1, b = f._aiWorldBounds();
    const walled = !!(typeof currentArena !== 'undefined' && currentArena && currentArena.worldWidth);
    let land = f.cx() + dir * m[4];
    if (walled) land = Math.max(b.left + 20, Math.min(b.right - 20, land));
    if (!_btGroundAt(land, f.y + f.h)) return -1;
  }
  const u = m[1] > m[0] ? Math.max(0, Math.min(1, (d - m[0]) / (m[1] - m[0]))) : 0;
  return m[2] + (m[3] - m[2]) * u;
}

// Should the bot throw this move right now? lock = frames the target is still
// held (stun, ragdoll or recovery). null = no opinion.
function botMoveWants(f, kind, t, lock, urgent) {
  const tth = botMoveTime(f, kind, t);
  if (tth === null) return null;
  if (tth < 0) return false;
  // A fresh guard can parry it.
  if (t.shielding && (t.shieldHoldTimer || 0) <= 15) return false;
  if (lock > 0 && tth <= lock + 4) return true;
  // In the open: fast enough to be hard to walk out of, thrown from range, or a
  // move that travels (a slow dash is still how that kit closes distance).
  // urgent = a full meter that has waited long enough; anything in band will do.
  const d = Math.abs(t.cx() - f.cx()), m = BOT_MOVES[f.weaponKey] && BOT_MOVES[f.weaponKey][kind];
  return tth <= (urgent ? 50 : 20) || d >= 170 || (!!m && m[4] >= 100 && d >= 90);
}

// Called by Fighter.ability() / useSuper() while the old brain is running:
// its random casts only go through when the move can actually connect.
function botTacVeto(f, kind, t) {
  if (!botTacSkill(f)) return false;
  if (kind === 'a') return _btFc() < (f._btSwingAt || 0);
  const tt = t || f.target;
  if (!tt) return false;
  const lock = Math.max(tt.stunTimer || 0, tt.ragdollTimer || 0, tt.attackEndlag || 0);
  return botMoveWants(f, kind, tt, lock) === false;
}

function _btGuardUp(f, frames) {
  if (!f.onGround || f.shielding) return f.shielding;
  if (typeof shieldRaise !== 'function' || !shieldRaise(f)) return false;
  f.shielding = true;
  f._btGuardUntil = _btFc() + frames;
  return true;
}

function _btGuardDown(f) {
  f.shielding = false; f.shieldHoldTimer = 0; f.shieldBroken = false; f._btGuardUntil = 0;
}

// Same height is not always reachable: a gap in the floor needs a routed hop,
// which only the old brain's pathfinding makes. Different heights stay here,
// since the old brain walks off floating decks otherwise.
function _btGroundY(x, feet) {
  let gy = null;
  for (const pl of currentArena.platforms) {
    if (pl.isFloorDisabled || x <= pl.x || x >= pl.x + pl.w || pl.y < feet - 12) continue;
    if (gy === null || pl.y < gy) gy = pl.y;
  }
  return gy;
}

function _btPitBetween(f, t) {
  if (typeof currentArena === 'undefined' || !currentArena || !currentArena.platforms) return false;
  const y = _btGroundY(f.cx(), f.y + f.h), ty = _btGroundY(t.cx(), t.y + t.h);
  if (y === null || ty === null || Math.abs(y - ty) > 12) return false;
  const x0 = Math.min(f.cx(), t.cx()), x1 = Math.max(f.cx(), t.cx());
  for (let x = x0 + 16; x < x1; x += 16) {
    const gy = _btGroundY(x, y);
    if (gy === null || gy > y + 130) return true;
  }
  return false;
}

// Knocked off the edge: steer for the nearest floor every frame, and spend the
// double jump once the fall starts.
function _btRecover(f, spd) {
  if (f.onGround || typeof currentArena === 'undefined' || !currentArena || !currentArena.platforms) return false;
  const feet = f.y + f.h, x = f.cx();
  if (_btGroundY(x, feet) !== null) return false;
  let best = null, bd = Infinity;
  for (const pl of currentArena.platforms) {
    if (pl.isFloorDisabled || pl.y < feet - 150) continue;      // too far above to reach
    const tx = Math.max(pl.x + 24, Math.min(pl.x + pl.w - 24, x));
    const dd = Math.abs(tx - x) + Math.max(0, feet - pl.y) * 0.5;
    if (dd < bd) { bd = dd; best = { tx, y: pl.y }; }
  }
  if (!best) return false;
  const dir = best.tx >= x ? 1 : -1;
  if (Math.abs(best.tx - x) > 6) { f.vx = dir * spd; f.facing = dir; }
  if (f.canDoubleJump && f.vy > 1 && feet > best.y - 40) { f.vy = -17; f.canDoubleJump = false; }
  return true;
}

// A target on another platform. The launch spot and speed come from the
// pathfinder's arc simulator and are held for the whole flight. The tick brain
// missed its climbs and paced under the platform.
function _btPlatUnder(x, feet) {
  const pls = currentArena.platforms;
  let bi = -1;
  for (let i = 0; i < pls.length; i++) {
    const pl = pls[i];
    if (pl.isFloorDisabled || x < pl.x || x > pl.x + pl.w || pl.y < feet - 8) continue;
    if (bi < 0 || pl.y < pls[bi].y) bi = i;
  }
  return bi;
}

// First platform to step to on the way from P to T.
function _btNextPlat(P, T, x, tx) {
  const g = typeof currentPlatformGraph !== 'undefined' ? currentPlatformGraph : null;
  if (!g || !g.platNodes || typeof pfAStar !== 'function') return T;
  const a = _pfNearestNodeOnPlat(g, P, x), b = _pfNearestNodeOnPlat(g, T, tx);
  if (a === null || b === null) return T;
  const path = pfAStar(g, a, b);
  if (!path) return T;
  for (const st of path) {
    const n = g.getNode(st.nodeId);
    if (n && n.platIdx !== P && currentArena.platforms[n.platIdx]) return n.platIdx;
  }
  return T;
}

// Platforms a flight from around x could touch. Story worlds run to hundreds.
let _btNearKey = '', _btNearList = [];
function _btNear(x) {
  const pls = currentArena.platforms, key = (currentArena.id || currentArena.name || '') + ':' + pls.length + ':' + Math.round(x / 300);
  if (key === _btNearKey) return _btNearList;
  _btNearKey = key; _btNearList = [];
  for (let i = 0; i < pls.length; i++) {
    const pl = pls[i];
    if (!pl.isFloorDisabled && pl.x < x + 900 && pl.x + pl.w > x - 900) _btNearList.push(i);
  }
  return _btNearList;
}

// One flight of the whole body box from platform P. Returns where it lands on N
// and after how many frames, or null if it clips a platform or leaves the arena.
// (The pathfinder's arc is a single point, which fits through gaps a body does not.)
function _btArc(f, x, vx, vy, dbl, P, N) {
  const pls = currentArena.platforms, near = _btNear(x), hw = f.w / 2, h = f.h;
  const g = pfArenaGravity(currentArena), vmax = currentArena.isLowGravity ? 10 : 19;
  const bottom = currentArena.deathY || 700, step = vy === 0;
  let y = pls[P].y, fired = false;
  for (let n = 0; n < 260; n++) {
    const py = y;
    if (dbl && !fired && vy >= -1) { vy = -17; fired = true; }
    vy = Math.min(vy + g, vmax); x += vx; y += vy;
    for (let k = 0; k < near.length; k++) {
      const i = near[k], pl = pls[i];
      if (x + hw <= pl.x || x - hw >= pl.x + pl.w) continue;
      if (vy > 0 && py <= pl.y + 2 && y >= pl.y) {
        if (i === P && (n < 8 || step)) continue;
        return i === N && !pl.isBouncy ? { x, frame: n } : null;
      }
      if (pl.passUnder || (i === P && step)) continue;
      if (y > pl.y && y - h < pl.y + (pl.h || 20)) return null;
    }
    if (y >= bottom) return null;
  }
  return null;
}

// Quickest way off platform P onto N: a spot to jump from, or an end to step off.
function _btPlanHop(f, P, N, spd) {
  const pls = currentArena.platforms, A = pls[P], B = pls[N], x = f.cx(), hw = f.w / 2;
  const inset = Math.min(22, B.w * 0.2);
  let best = null, bc = Infinity;
  const tryAt = (lx, vx, vy, dbl) => {
    const walk = Math.abs(lx - x) / spd;                    // cost is frames: the walk, then the flight
    if (walk >= bc) return;
    // A step off starts falling once the whole body is past the end.
    const r = _btArc(f, vy ? lx : lx + Math.sign(vx) * (hw + 3), vx, vy, dbl, P, N);
    if (!r || r.x < B.x + 8 || r.x > B.x + B.w - 8) return;
    // Touching down near an end is a last resort.
    const cost = walk + r.frame + (r.x < B.x + inset || r.x > B.x + B.w - inset ? 45 : 0);
    if (cost >= bc) return;
    bc = cost; best = { x: lx, vx, vy, dbl, P, N };
  };
  const lo = Math.max(A.x + hw, B.x - 340), hi = Math.min(A.x + A.w - hw, B.x + B.w + 340);
  // A full jump first; under a low ceiling only a shorter one fits; the double
  // jump only when nothing else gets there.
  for (const vy of [-20, -15, -11, 0]) {
    if (best) break;
    for (let lx = lo; lx <= hi; lx += 16) {
      for (const m of [1, 0.6, 0.25]) { tryAt(lx, spd * m, vy || -20, !vy); tryAt(lx, -spd * m, vy || -20, !vy); }
    }
  }
  if (B.y > A.y) {
    for (const m of [1, 0.5]) { tryAt(A.x + A.w - 2, spd * m, 0, false); tryAt(A.x + 2, -spd * m, 0, false); }
  }
  return best;
}

// No hop straight there and no route in the graph: one platform in between.
function _btPlanVia(f, P, T, spd, not) {
  const pls = currentArena.platforms, B = pls[T], x = f.cx();
  let best = null, bc = Infinity;
  for (let K = 0; K < pls.length; K++) {
    const pk = pls[K];
    if (K === P || K === T || K === not || pk.isFloorDisabled || pk.isCeiling || pk.x > B.x + B.w + 500 || pk.x + pk.w < B.x - 500 ||
        Math.abs(pk.y - B.y) > 420) continue;
    const mid = Math.max(pk.x, Math.min(pk.x + pk.w, B.x + B.w / 2));
    if (!_btPlanHop({ cx: () => mid, w: f.w, h: f.h }, K, T, spd)) continue;
    const pl = _btPlanHop(f, P, K, spd);
    if (!pl) continue;
    const cost = Math.abs(pl.x - x) + Math.abs(mid - pl.x) + Math.abs(pk.y - B.y);
    if (cost < bc) { bc = cost; best = pl; }
  }
  return best;
}

// The planned flight: hold its speed, fire the double jump at the top.
function _btFly(f) {
  const j = f._btJump;
  if (f.hurtTimer > 0 || ++j.n > 150) { f._btJump = null; return false; }
  if (!f.onGround) j.left = true;
  else if (j.left || j.n > 30) { f._btJump = null; return false; }
  f.vx = j.vx;
  if (j.dbl && j.left && f.canDoubleJump && f.vy >= -1) { f.vy = -17; f.canDoubleJump = false; j.dbl = false; }
  f._btNavFc = _btFc();
  return true;
}

let _btPlanFc = -1;
function _btLevel(f, t, spd, d, dir) {
  if (!f.onGround || typeof pfArenaGravity !== 'function' || typeof currentArena === 'undefined' ||
      !currentArena || !currentArena.platforms) return false;
  const feet = f.y + f.h, tFeet = t.y + t.h;
  if (d > 760) return false;
  // Two bots heading for each other's platforms would swap places for good, so only the higher one drops.
  if (t.isAI && feet > tFeet && botTacSkill(t) >= 0.7) return false;
  const pls = currentArena.platforms;
  const P = _btPlatUnder(f.cx(), feet), T = _btPlatUnder(t.cx(), tFeet);
  if (P < 0 || T < 0 || P === T || Math.abs(pls[P].y - feet) > 8) return false;
  // Level with each other counts only across open air, not along a tiled floor.
  if (Math.abs(pls[P].y - pls[T].y) <= 40 &&
      Math.max(pls[P].x - pls[T].x - pls[T].w, pls[T].x - pls[P].x - pls[P].w) < 30) return false;
  const fc = _btFc();
  let pl = f._btHop;
  if (!pl || pl.P !== P || pl.T !== T || fc >= pl.until) {
    if (f._btHopNo === P * 1000 + T && fc < (f._btHopNoUntil || 0)) return false;
    // A search can cost several ms: one bot per frame.
    if (_btPlanFc === fc) return false;
    _btPlanFc = fc;
    // Straight there if one flight does it; else the graph's next platform, else
    // any platform that has a flight on. Never back to the one just left.
    const was = fc < (f._btWasUntil || 0) ? f._btWas : -1;
    pl = _btPlanHop(f, P, T, spd);
    if (!pl) {
      const N = _btNextPlat(P, T, f.cx(), t.cx());
      pl = (N !== T && N !== was ? _btPlanHop(f, P, N, spd) : null) || _btPlanVia(f, P, T, spd, was);
    }
    if (!pl) { f._btHop = null; f._btHopNo = P * 1000 + T; f._btHopNoUntil = fc + 75; return false; }
    pl.T = T; pl.until = fc + 90;
    f._btHop = pl;
  }
  f._wanderTimer = 0; f._inactiveTime = 0; f._stuckFrames = 0; f.aiNoHitTimer = 0;
  f._btPlan = null;
  f._btNavFc = fc;
  if (f.shielding) _btGuardDown(f);
  // They dropped into reach on the way: take the swing.
  if (d <= _btReach(f, t) && Math.abs(feet - tFeet) <= 70) _btSwing(f, t, dir);
  const dx = pl.x - f.cx();
  if (Math.abs(dx) > spd) { f.vx = Math.sign(dx) * spd; f.facing = Math.sign(dx); return true; }
  if (f._landLag > 0 || f.attackEndlag > 0) { f.vx = 0; return true; }
  f.x += dx;
  f.vx = pl.vx; f.facing = pl.vx >= 0 ? 1 : -1;
  if (pl.vy) { f.vy = pl.vy; f.canDoubleJump = true; }
  f._btJump = { vx: pl.vx, dbl: pl.dbl, n: 0, left: false };
  f._btHop = null; f._btWas = P; f._btWasUntil = fc + 300;
  return true;
}

function _btMove(f, dir, v) {
  if (dir === 0) { f.vx *= 0.6; return true; }
  if (f.isEdgeDanger(dir)) { f.vx = 0; return false; }
  f.vx = dir * v;
  return true;
}

// Incoming shots: jump the early ones, guard the late ones. A shot has to be in
// the air for the bot's reaction time first, so close shots land, as they do on a person.
function _btDodge(f, t, sk) {
  if (!f.onGround) return false;
  const fc = _btFc(), react = Math.round(19 - 8 * sk);
  const pools = [typeof projectiles !== 'undefined' ? projectiles : null,
                 t._boomerangs, t._paperPlanes, t._wxBolts, t._wxKnives];
  for (const pool of pools) {
    if (!pool) continue;
    for (const pr of pool) {
      if (!pr || pr.active === false || pr.owner === f || pr._btSeen === f) continue;
      if (pr.owner && typeof isHostileTarget === 'function' && !isHostileTarget(f, pr.owner)) continue;
      if (pr._btBorn === undefined) pr._btBorn = fc;
      if (fc - pr._btBorn < react) continue;
      const vx = pr.vx || 0;
      if (Math.abs(vx) < 2) continue;
      const gap = f.cx() - pr.x;
      if (gap * vx <= 0) continue;                         // moving away
      if (Math.abs(pr.y - f.cy()) > f.h * 0.6 + 12) continue;
      const tti = Math.abs(gap) / Math.abs(vx);
      if (tti > 10) continue;
      pr._btSeen = f;                                      // one decision per shot
      if (Math.random() > 0.2 + 0.5 * sk) return false;
      if (tti >= 5 && !f.isEdgeDanger(t.cx() >= f.cx() ? 1 : -1)) { f.vy = -17; return true; }
      return _btGuardUp(f, Math.ceil(tti) + 4);
    }
  }
  return false;
}

// Throw E, else Q, if either connects inside `lock` frames (or suits the open
// field when lock is 0). Returns true when something was cast.
function _btCast(f, t, lock, allowQ) {
  if (f.superReady && !f._storyNoSuper && botMoveWants(f, 'e', t, lock, (f._btSuperAge || 0) > 75) === true) {
    const m0 = f.superMeter;
    f.useSuper(t);
    if (f.superMeter < m0 || !f.superReady) return true;
  }
  if (allowQ && (f.abilityCooldown || 0) <= 0 && !(f.attackEndlag > 0) && botMoveWants(f, 'q', t, lock) === true) {
    f.ability(t);
    if ((f.abilityCooldown || 0) > 0) return true;
  }
  return false;
}

// free = the swing is a follow-up or a punish, so the bot's hesitation does not apply.
function _btSwing(f, t, dir, free) {
  if ((f.cooldown || 0) > 0 || f.attackEndlag > 0 || f.attackTimer > 0) return false;
  const fc = _btFc();
  if (!free && fc < (f._btSwingAt || 0)) return false;
  f.facing = dir;
  f.attack(t);
  if (!(f.attackTimer > 0)) return false;
  const hes = (typeof f._botIQ === 'number' ? 0 : BOT_TACTICS.hesitate[f.aiDiff]) || 0;
  f._btSwingAt = fc + (f.cooldown || 0) + Math.floor(Math.random() * (hes + 1));
  return true;
}

// Keep the target in the band where shots land clean but its weapon does not
// reach. Backing up stops at a wall or ledge. After a long retreat the bot stands
// and fights, so it never runs for a whole match.
function _btRangedMove(f, t, d, dir, spd, sk) {
  const TR = (t.weapon && t.weapon.type === 'melee') ? _btReach(t, f) : 60;
  const band = BOT_RANGED_BAND[f.weaponKey];
  const lo = band ? Math.max(band[0], TR + 20) : Math.max(150, TR + 45);
  const hi = band ? band[1] : Math.min(300, (f.weapon.range || 500) * 0.6);
  const fc = _btFc();
  if (fc < (f._btStandUntil || 0)) { _btMove(f, 0, 0); return; }
  if (d < lo) {
    f._btRetreat = (f._btRetreat || 0) + 1;
    if (f._btRetreat > 110 + 80 * sk) { f._btRetreat = 0; f._btStandUntil = fc + 50; return; }
    const b = f._aiWorldBounds();
    const cornered = (dir > 0 ? f.x < b.left + 46 : f.x + f.w > b.right - 46) || f.isEdgeDanger(-dir);
    if (!cornered) { f.vx = -dir * spd * (0.85 + 0.15 * sk); return; }
    if (f.onGround && d < 150 && fc >= (f._btHopAt || 0) && !f.isEdgeDanger(dir)) {
      f._btHopAt = fc + 90;
      f.vy = -19; f.vx = dir * spd * 1.5;
      return;
    }
    _btMove(f, 0, 0);
    return;
  }
  f._btRetreat = Math.max(0, (f._btRetreat || 0) - 2);
  if (d > hi) _btMove(f, dir, spd);
  else _btMove(f, 0, 0);
}

function _btRanged(f, t, d, dir, sk, lock) {
  const w = f.weapon;
  const arcs = f.weaponKey === 'slingshot' || f.weaponKey === 'bomb';
  const level = arcs || Math.abs((f.y + f.h) - (t.y + t.h)) < 70;
  f._btSuperAge = f.superReady ? (f._btSuperAge || 0) + 1 : 0;
  if (f.onGround && (lock > 0 || f._btSuperAge > 45 || d > 150) && _btCast(f, t, lock, true)) return;
  // Shoot the frame the weapon is ready instead of on the next AI tick, but not
  // into the point-blank penalty (Fighter.attack) unless there is nowhere to go.
  const reloading = !!(w.clipSize && f._reloadTimer > 0);
  const pb = 0;
  const maxD = f.weaponKey === 'flamethrower' ? 215 : (w.range || 500);
  if (!reloading && level && (f.cooldown || 0) <= 0 && d >= pb && d <= maxD &&
      !(t.shielding && (t.shieldHoldTimer || 0) <= 15 && d < 200)) {
    f.facing = dir;
    f.attack(t);
  }
}

function botTacticsFrame(f) {
  const sk = botTacSkill(f);
  if (!sk) return;
  const fc = _btFc();
  if (f._btGuardUntil && fc >= f._btGuardUntil) _btGuardDown(f);
  // The old brain counts these down once per AI tick but sets them in frames, so
  // a 45-frame wander lasted 11 seconds. Cap them at what was meant.
  if (f._wanderTimer > 3)    f._wanderTimer = 3;
  if (f._intentTimer > 5)    f._intentTimer = 5;
  if (f._microRandTimer > 6) f._microRandTimer = 6;
  if (f._stateChangeCd > 2)  f._stateChangeCd = 2;
  const t = f.target;
  if (!t || !(t.health > 0) || !(f.health > 0) || !f.weapon) return;
  if (f.stunTimer > 0 || f.ragdollTimer > 0) { f._btWasHeld = true; return; }
  if (f.backstageHiding) return;
  if (typeof isCinematic !== 'undefined' && isCinematic) return;
  if (typeof MoveScene !== 'undefined' && MoveScene.isBusy(f)) return;
  if (f._aiClimbSteer || f._aiHop || f._megaJumping) return;
  if (f._btWasHeld) { f._btWasHeld = false; f._btWakeUntil = fc + 20; f._btWakeRoll = Math.random(); f._btJump = null; }
  if (f._btJump && _btFly(f)) return;
  if (BOT_TACTICS.recover && sk >= 0.7 && _btRecover(f, f.aiDiff === 'expert' ? 5.6 : 5.0)) return;
  // Hazards stay with the old brain, which knows lava and the boss floor.
  if (typeof bossFloorState !== 'undefined' && bossFloorState !== 'normal') return;
  if (typeof currentArena !== 'undefined' && currentArena && currentArena.hasLava && currentArena.lavaY &&
      currentArena.lavaY - (f.y + f.h) < 130) return;

  const dxv = t.cx() - f.cx(), d = Math.abs(dxv), dir = dxv >= 0 ? 1 : -1;
  if (BOT_TACTICS.level && sk >= 0.7 && f.weapon.type === 'melee' &&
      _btLevel(f, t, f.aiDiff === 'expert' ? 5.6 : 5.0, d, dir)) return;
  if (d > TAC_RANGE || Math.abs((f.y + f.h) - (t.y + t.h)) > TAC_LEVEL) { f._btPlan = null; return; }
  // Wander is cleared too: it returns before the chase that makes the jump.
  if (_btPitBetween(f, t)) { f._btPlan = null; f._wanderTimer = 0; return; }
  const think = (typeof f._botIQ === 'number' ? 0 : BOT_TACTICS.think[f.aiDiff]) || 1;
  if (think > 1) {
    if (f._btPhase === undefined) f._btPhase = Math.floor(Math.random() * think);
    if (fc % think !== f._btPhase) { f._wanderTimer = 0; return; }
  }

  // The old brain's idle / stuck / wander machinery would fight every choice below.
  f._wanderTimer = 0; f._inactiveTime = 0; f._stuckFrames = 0; f.aiNoHitTimer = 0; f._comboPressTimer = 0;

  const lock  = Math.max(t.stunTimer || 0, t.ragdollTimer || 0);
  const tRec  = Math.max(t.attackEndlag || 0, t._parryVulnFrames || 0);
  const open  = Math.max(lock, tRec);

  const spd = (f.aiDiff === 'easy' ? 3.4 : f.aiDiff === 'medium' ? 4.4 : f.aiDiff === 'hard' ? 5.0 : 5.6) *
              Math.max(0.25, f._aggroBoost || 1);

  if (f.weapon.type === 'ranged') {
    if (f.shielding) return;
    _btDodge(f, t, sk);
    // Ranged against ranged keeps the old close-quarters duel; only the firing is per-frame.
    if (f.onGround && !(t.weapon && t.weapon.type === 'ranged')) _btRangedMove(f, t, d, dir, spd, sk);
    _btRanged(f, t, d, dir, sk, open);
    return;
  }

  const R       = _btReach(f, t) - 3;
  const tMelee  = !!(t.weapon && t.weapon.type === 'melee');
  const TR      = tMelee ? _btReach(t, f) : 0;
  const tBusy   = typeof MoveScene !== 'undefined' && MoveScene.isBusy(t);
  const tReady  = tMelee && !open && (t.cooldown || 0) <= 0 && !(t.attackTimer > 0) && !tBusy;
  const meReady = (f.cooldown || 0) <= 0 && !(f.attackEndlag > 0) && !(f.attackTimer > 0);
  const tFresh  = !!t.shielding && (t.shieldHoldTimer || 0) <= 15;

  // One read per ~1s: does the bot play this stretch thoughtfully, or just run in?
  if (fc >= (f._btEpochEnd || 0)) {
    f._btEpochEnd = fc + 40 + Math.floor(Math.random() * 30);
    f._btSmart = Math.random() < 0.15 + 0.85 * sk;
  }
  const smart = f._btSmart;

  // Guard is up
  if (f.shielding) {
    // The guard did its job (they are stuck in a blocked or parried swing): take the turn.
    if (open > 0 && d <= R + spd * 3) { if (_btSwing(f, t, dir, true)) return; }
    _btMove(f, d > R - 8 ? dir : 0, spd * 0.4);
    return;
  }

  if (!tMelee && _btDodge(f, t, sk)) return;

  // They cannot act: continue the hit or punish the recovery
  if (open > 0) {
    _btMove(f, d > R - 10 ? dir : 0, spd * 1.15);
    if (!f.onGround) { _btSwing(f, t, dir, smart); return; }
    if (_btSwing(f, t, dir, smart)) return;
    if (!smart || f.attackTimer > 0 || f.attackEndlag > 0) return;
    const spent = (f._basicChainN || 0) >= (typeof BASIC_CHAIN_MAX !== 'undefined' ? BASIC_CHAIN_MAX : 2);
    // Another swing is still coming inside the window: let it.
    if (!spent && (f.cooldown || 0) < open && d - spd * open <= R) return;
    // The two-swing chain is spent, or they are out of reach: finish with a move.
    if (_btCast(f, t, open, true)) return;
    const capped = spent && meReady && d <= R;
    // A jumping swing is the other stance, so it reopens the chain.
    if (capped && sk >= 0.7 && lock >= 12 && fc >= (f._btHopAt || 0)) { f._btHopAt = fc + 40; f.vy = -11; }
    return;
  }

  // Just out of a combo, and they are standing over us ready to swing
  // Some of the time the answer is the guard, not another trade.
  if (BOT_TACTICS.guard && fc < (f._btWakeUntil || 0) && tReady && d <= TR + 24 && f.onGround) {
    f._btWakeUntil = 0;
    if (f._btWakeRoll < 0.1 + 0.4 * sk && _btGuardUp(f, TAC_GUARD + 6)) return;
  }

  // Their swing is live
  if (tMelee && t.attackTimer > 0 && d <= TR + 12) {
    // One read per swing: does the bot see it in time to put the guard up?
    // It has to have watched the swing for its reaction time first.
    if (fc - (f._btSwLast || -9) > 2) { f._btSwAt = fc; f._btSwGuard = smart && Math.random() < 0.1 + 0.35 * sk; }
    f._btSwLast = fc;
    if (BOT_TACTICS.guard && f._btSwGuard && f.onGround && fc - f._btSwAt >= Math.round(11 - 7 * sk)) {
      f._btSwGuard = false;
      if (_btGuardUp(f, TAC_GUARD)) return;
    }
    if (d <= R && _btSwing(f, t, dir)) return;            // trade
    _btMove(f, -dir, spd);
    return;
  }

  // Neutral
  f._btSuperAge = f.superReady ? (f._btSuperAge || 0) + 1 : 0;
  if (smart && f.onGround && !tFresh) {
    // A full meter is spent soon (holding it wastes meter and domain charges),
    // but on a throw that can land.
    if (f.superReady) {
      const tth = botMoveTime(f, 'e', t);
      if (tth !== null && tth >= 0 && (tth <= 14 || f._btSuperAge > 75 || !tReady) && _btCast(f, t, 0, false)) return;
    }
    // Q covers the ground the basic attack cannot.
    if (d > R + 12 && (f.abilityCooldown || 0) <= 0 && fc >= (f._btQAt || 0)) {
      f._btQAt = fc + 24;
      if (Math.random() < 0.3 + 0.5 * sk && botMoveWants(f, 'q', t, 0) === true) {
        f.ability(t);
        if ((f.abilityCooldown || 0) > 0) return;
      }
    }
  }

  if (meReady && !tFresh && _btSwing(f, t, dir)) return;

  let want;
  if (t.shielding) {
    // Never swing into a fresh guard. Stay where only our weapon reaches, or outside theirs.
    want = R > TR + 12 ? R - 6 : TR + 16;
    if (!tFresh && meReady && d <= R) _btSwing(f, t, dir);
  } else if (!meReady) {
    // Recovering: out of their reach if they can swing, else stay on them.
    want = (smart && tReady) ? Math.max(TR + 14, R - 6) : R - 8;
  } else if (R > TR + 12 || !tReady || !smart) {
    // We outrange them, or they cannot swing yet: hold our own distance / go.
    want = (R > TR + 12 && tReady && smart) ? Math.max(R - 8, TR + 8) : R - 10;
  } else {
    // They reach at least as far and are ready. Crossing their range is the
    // dangerous part, so pick how once per approach.
    if (!f._btPlan || d > TR + 70) {
      const r = Math.random();
      f._btPlan = r < 0.45 ? 'guard' : r < 0.8 ? 'bait' : 'rush';
      f._btBaitUntil = fc + 26 + Math.floor(Math.random() * 40 * (1.3 - sk));
    }
    if (f._btPlan === 'bait' && fc >= f._btBaitUntil) f._btPlan = 'guard';
    if (f._btPlan === 'guard' && (f._shieldDownFrames || 0) < 20 && d <= TR + 30) f._btPlan = 'rush';
    if (f._btPlan === 'bait') {
      // Hover at the edge of their reach, stepping in and out to draw the swing.
      want = TR + 16 + ((fc >> 4) & 1 ? 10 : -4);
    } else {
      want = R - 10;
      if (f._btPlan === 'guard' && d <= TR + 8 && _btGuardUp(f, TAC_GUARD)) { f._btPlan = null; return; }
    }
  }
  const err = d - want;
  if (err > 6) _btMove(f, dir, spd);
  else if (err < -6) { if (!_btMove(f, -dir, spd * 0.85)) f._btPlan = 'rush'; }
  else _btMove(f, 0, 0);
}
