"""Renders tools/voice/lines.json to audio/voice/<key>.mp3 with Kokoro, then writes js/smb-voice-manifest.js.

Setup (once):  python3 -m venv tools/voice/.venv && tools/voice/.venv/bin/pip install kokoro-onnx soundfile
               model files from github.com/thewh1teagle/kokoro-onnx releases (model-files-v1.0) into tools/voice/model/
Run from repo root:  node tools/voice/extract-lines.js && tools/voice/.venv/bin/python tools/voice/render.py
Only missing lines are rendered. Pass --force to re-render everything (after changing VOICES).
--shard=I/N renders every Nth missing line and skips the manifest, so several processes can share the work;
finish with a plain run to write the manifest.
"""
import json, os, re, subprocess, sys, tempfile
import soundfile as sf
from kokoro_onnx import Kokoro

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
OUT_DIR = os.path.join(ROOT, 'audio', 'voice')
MANIFEST = os.path.join(ROOT, 'js', 'smb-voice-manifest.js')

# speaker -> (kokoro voice, speed). Speakers are StoryVoice's: 'none' narration, 'npc', 'player', or a fightScript name.
VOICES = {
    'none':     ('af_heart',   0.95),
    'npc':      ('am_fenrir',  0.95),
    'player':   ('am_michael', 1.0),
    'KAEL':     ('am_michael', 1.0),
    'YOU':      ('am_michael', 1.0),
    'GUIDE':    ('bf_emma',    1.0),
    'GOD':      ('bm_george',  0.85),
    '_default': ('af_heart',   0.95),
}


def clean(text):
    t = re.sub(r'[☀-➿\U0001F000-\U0001FFFF️]', '', text)  # emoji and symbols
    t = t.replace('"', '').replace('“', '').replace('”', '')
    t = re.sub(r'\s+', ' ', t).strip()
    return t


def main():
    force = '--force' in sys.argv
    shard = next((a.split('=')[1] for a in sys.argv if a.startswith('--shard=')), None)
    lines = json.load(open(os.path.join(HERE, 'lines.json')))
    os.makedirs(OUT_DIR, exist_ok=True)
    k = Kokoro(os.path.join(HERE, 'model', 'kokoro-v1.0.onnx'), os.path.join(HERE, 'model', 'voices-v1.0.bin'))
    keys = set()
    todo = [l for l in lines if force or not os.path.exists(os.path.join(OUT_DIR, l['key'] + '.mp3'))]
    if shard:
        si, sn = map(int, shard.split('/'))
        todo = todo[si::sn]
    print(f'{len(lines)} lines, {len(todo)} to render', flush=True)
    for i, l in enumerate(todo):
        voice, speed = VOICES.get(l['speaker'], VOICES['_default'])
        text = clean(l['text'])
        if not text:
            continue
        lang = 'en-gb' if voice[0] == 'b' else 'en-us'
        samples, sr = k.create(text, voice=voice, speed=speed, lang=lang)
        with tempfile.NamedTemporaryFile(suffix='.wav', delete=False) as tmp:
            sf.write(tmp.name, samples, sr)
        subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', tmp.name, '-ac', '1', '-ar', '24000',
                        '-c:a', 'libmp3lame', '-b:a', '40k', os.path.join(OUT_DIR, l['key'] + '.mp3')], check=True)
        os.unlink(tmp.name)
        if i % 25 == 0:
            print(f'  {i + 1}/{len(todo)}', flush=True)
    if shard:
        return

    for l in lines:
        if os.path.exists(os.path.join(OUT_DIR, l['key'] + '.mp3')):
            keys.add(l['key'])
    for f in os.listdir(OUT_DIR):
        if f.endswith('.mp3') and f[:-4] not in keys:
            os.unlink(os.path.join(OUT_DIR, f))
    with open(MANIFEST, 'w') as fh:
        fh.write('// Generated by tools/voice/render.py. Keys of story lines with a recorded file in audio/voice/.\n')
        fh.write('const STORY_VOICE_LINES = new Set(' + json.dumps(sorted(keys)) + ');\n')
    print(f'manifest: {len(keys)} lines', flush=True)


if __name__ == '__main__':
    main()
