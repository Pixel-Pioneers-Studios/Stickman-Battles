'use strict';
/*
 * tools/sov-discoveries-doc.js — WRITE DOWN WHAT HE FOUND. DEV ONLY.
 *
 * Reads the lineage dumps from tools/sov-discover.js and writes
 * docs/sovereign-discoveries.md. Nothing in the document is our opinion: every
 * number is his own estimate, pooled across independent lineages, and every
 * claim is labelled by how many lineages reached it on their own.
 *
 * Usage: node tools/sov-discoveries-doc.js data/discover/<stamp> [--out=docs/sovereign-discoveries.md]
 */
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/sov-discoveries-doc.js data/discover/<stamp>'); process.exit(1); }
const outArg = process.argv.find(a => a.startsWith('--out='));
const OUT = outArg ? outArg.slice(6) : path.join(ROOT, 'docs', 'sovereign-discoveries.md');

const L = fs.readdirSync(dir).filter(f => /^lineage-\d+\.json$/.test(f)).sort()
  .map(f => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
if (!L.length) { console.error('no lineage dumps in ' + dir); process.exit(1); }
const NL = L.length;

// ── helpers ─────────────────────────────────────────────────────────────────
const mean = c => c && c.n ? c.r / c.n : null;
const se = c => {
  if (!c || c.n < 2) return null;
  const m = c.r / c.n, v = Math.max(0, c.r2 / c.n - m * m);
  return Math.sqrt(v / c.n);
};
const f1 = v => v === null || v === undefined ? '—' : (v >= 0 ? '+' : '') + v.toFixed(1);
const pool = (cells) => {
  const o = { n: 0, r: 0, r2: 0, dealt: 0, taken: 0, frames: 0 };
  for (const c of cells) if (c) for (const k of Object.keys(o)) o[k] += c[k] || 0;
  return o;
};
// Pooled cell for (key, field, option) across lineages.
const pooled = (key, field, opt) => pool(L.map(l => l.arsenal && l.arsenal[key] && l.arsenal[key][field][opt]));
// Per-lineage rank of every option under a key (by mean, min n).
function ranks(key, field, minN) {
  return L.map(l => {
    const t = (l.arsenal && l.arsenal[key] && l.arsenal[key][field]) || {};
    return Object.keys(t).filter(k => t[k].n >= minN).map(k => ({ k, m: mean(t[k]) }))
      .sort((a, b) => b.m - a.m).map(x => x.k);
  });
}

const weapons = L[0].weapons, classes = L[0].classes;
const totalMatches = L.reduce((a, l) => a + l.hist.length, 0);
const totalLives = L.reduce((a, l) => a + ((l.arsenal && l.arsenal.any) ?
  Object.values(l.arsenal.any.weapon).reduce((s, c) => s + c.n, 0) : 0), 0);

let md = '';
const p = s => { md += s + '\n'; };

p('# Sovereign\'s discoveries');
p('');
p(`*Generated by \`tools/sov-discoveries-doc.js\` from \`${path.relative(ROOT, dir)}\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand; re-run the tool.*`);
p('');
p('Everything below is what Sovereign concluded from his own fights. We did not tell him which weapons are strong, which counter what, or how any mechanic works. His job was to find out. Ours is to write it down.');
p('');
p('## How he found it');
p('');
p(`- **${NL} independent lineages** × ${L[0].matches} matches = **${totalMatches} matches, ${totalLives} lives**. Each lineage started with an empty memory and its own random stream. A result one lineage reaches is a hypothesis; one that most lineages reach on their own is a finding.`);
p(`- **Fair opponents.** Stock stats, the game's own expert AI, no scripted policy. Opponents cycled through all ${weapons.length} legal weapons; their class was random.`);
p(`- **Open choice.** Every match he picked any of ${weapons.length} weapons and ${classes.length} classes (Megaknight excluded as admin-only), with no priors and no counter bonus from us. He chose by Thompson sampling over his own results, so kits he'd barely tried still got tried.`);
p('- **His score** for a life is net damage per 1000 frames (dealt − taken). Positive means he was winning the exchange while holding that kit.');
p(`- **His brain:** \`${L[0].flags.join(', ')}\`.`);
p('');

// ── What he settled on ──────────────────────────────────────────────────────
p('## What he settled on');
p('');
p('His picks in the last 20% of each lineage, after he had learned. When independent lineages converge on the same kit, that\'s his answer to "what is strongest here".');
p('');
p('| lineage | top weapons (share of picks) | top classes |');
p('|---|---|---|');
const convergedW = {}, convergedC = {};
for (const l of L) {
  const tail = l.hist.slice(Math.floor(l.hist.length * 0.8)).filter(h => h.w);
  const cw = {}, cc = {};
  for (const h of tail) { cw[h.w] = (cw[h.w] || 0) + 1; cc[h.c] = (cc[h.c] || 0) + 1; }
  const fmt = o => Object.entries(o).sort((a, b) => b[1] - a[1]).slice(0, 3)
    .map(([k, v]) => `${k} ${Math.round(100 * v / tail.length)}%`).join(', ');
  const topW = Object.entries(cw).sort((a, b) => b[1] - a[1])[0];
  const topC = Object.entries(cc).sort((a, b) => b[1] - a[1])[0];
  if (topW) convergedW[topW[0]] = (convergedW[topW[0]] || 0) + 1;
  if (topC) convergedC[topC[0]] = (convergedC[topC[0]] || 0) + 1;
  p(`| ${l.lineage} | ${fmt(cw)} | ${fmt(cc)} |`);
}
p('');
const agreeLine = (o, what) => Object.entries(o).sort((a, b) => b[1] - a[1])
  .map(([k, v]) => `**${k}** (${v}/${NL})`).join(', ');
p(`Most-picked ${'weapon'} by lineage: ${agreeLine(convergedW)}. Most-picked class: ${agreeLine(convergedC)}.`);
p('');

// ── Weapons ─────────────────────────────────────────────────────────────────
function tierTable(field, opts, label) {
  const R = ranks('any', field, 10);
  const rows = opts.map(o => {
    const c = pooled('any', field, o);
    const top = R.filter(r => r.slice(0, 3).includes(o)).length;
    const bot = R.filter(r => r.length >= 6 && r.slice(-3).includes(o)).length;
    return { o, c, m: mean(c), s: se(c), top, bot };
  }).filter(x => x.c.n > 0).sort((a, b) => b.m - a.m);
  p(`| ${label} | his estimate (net/1000f) | ± | lives | dealt/1000f | taken/1000f | top-3 in | bottom-3 in |`);
  p('|---|---|---|---|---|---|---|---|');
  for (const x of rows) {
    const d = x.c.frames ? x.c.dealt / x.c.frames * 1000 : 0, t = x.c.frames ? x.c.taken / x.c.frames * 1000 : 0;
    p(`| ${x.o} | ${f1(x.m)} | ${x.s === null ? '—' : x.s.toFixed(1)} | ${x.c.n} | ${d.toFixed(1)} | ${t.toFixed(1)} | ${x.top}/${NL} | ${x.bot}/${NL} |`);
  }
  const never = opts.filter(o => !rows.find(r => r.o === o));
  if (never.length) p(`\nNever held long enough to score: ${never.join(', ')}.`);
  p('');
  return rows;
}
p('## Weapons, as he ranks them');
p('');
p('Pooled across lineages. "top-3 in" counts the lineages that independently put the weapon in their top three (lives ≥ 10).');
p('');
const wRows = tierTable('weapon', weapons, 'weapon');

p('## Classes, as he ranks them');
p('');
p('Class stats are real in this mode: HP and speed are scaled onto his stat line by the class\'s own values, so a tanky or fragile class shows up as such.');
p('');
tierTable('cls', classes, 'class');

// ── Counters ────────────────────────────────────────────────────────────────
p('## Counters he found');
p('');
p('For each opponent weapon, his best weapon against it (lives ≥ 6) and how many lineages found the same answer on their own. A counter is marked **agreed** when more than half the lineages picked it.');
p('');
p('| opponent holds | his best answer | net/1000f | lives | lineages agreeing | runner-up | his worst pick |');
p('|---|---|---|---|---|---|---|');
for (const ow of weapons) {
  const key = 'ow:' + ow;
  const R = ranks(key, 'weapon', 6);
  const cand = {};
  for (const w of weapons) { const c = pooled(key, 'weapon', w); if (c.n >= 6) cand[w] = c; }
  const sorted = Object.entries(cand).sort((a, b) => mean(b[1]) - mean(a[1]));
  if (!sorted.length) { p(`| ${ow} | not enough data | | | | | |`); continue; }
  const [bw, bc] = sorted[0];
  const agree = R.filter(r => r[0] === bw).length;
  const ru = sorted[1] ? `${sorted[1][0]} (${f1(mean(sorted[1][1]))})` : '—';
  const worst = sorted.length > 2 ? `${sorted.at(-1)[0]} (${f1(mean(sorted.at(-1)[1]))})` : '—';
  p(`| ${ow} | ${agree > NL / 2 ? '**' + bw + '** (agreed)' : bw} | ${f1(mean(bc))} | ${bc.n} | ${agree}/${NL} | ${ru} | ${worst} |`);
}
p('');

// ── Opponent weapons ────────────────────────────────────────────────────────
p('## Which opponent weapons gave him the most trouble');
p('');
p('His average result against each opponent weapon, over every kit he tried against it. Lower means harder for him. This reflects the weapon in the hands of the game\'s AI, and it\'s partly shaped by his own choices, since he learns counters as he goes.');
p('');
p('| opponent weapon | his net/1000f against it | lives |');
p('|---|---|---|');
const oppRows = weapons.map(ow => {
  const cells = [];
  for (const l of L) { const b = l.arsenal && l.arsenal['ow:' + ow]; if (b) cells.push(...Object.values(b.weapon)); }
  const c = pool(cells);
  return { ow, c, m: mean(c) };
}).filter(x => x.c.n).sort((a, b) => a.m - b.m);
for (const x of oppRows) p(`| ${x.ow} | ${f1(x.m)} | ${x.c.n} |`);
p('');

// ── Mechanics ───────────────────────────────────────────────────────────────
p('## Mechanics he inferred');
p('');
p('From his prediction-failure engine: swings he expected to land that didn\'t, and what was true when they failed. He is never shown any mechanic\'s code, constants or flags.');
p('');
const failAgree = {}, hurtAgree = {};
for (const l of L) {
  for (const r of l.failRules || []) (failAgree[r.when] = failAgree[r.when] || []).push(r);
  for (const r of l.hurtRules || []) (hurtAgree[r.when] = hurtAgree[r.when] || []).push(r);
}
p(`Base failure rate of a swing he expected to land: ${L.map(l => l.mech ? (100 * l.mech.miss / l.mech.n).toFixed(0) + '%' : '—').join(' / ')} (per lineage).`);
p('');
p('**"Why didn\'t my hit land?"**');
p('');
p('| condition | lineages | fail rate | lift | reads as |');
p('|---|---|---|---|---|');
const fr = Object.entries(failAgree).sort((a, b) => b[1].length - a[1].length || b[1][0].lift - a[1][0].lift);
for (const [k, v] of fr.slice(0, 15)) {
  const avg = f => v.reduce((a, r) => a + r[f], 0) / v.length;
  p(`| \`${k}\` | ${v.length}/${NL} | ${(100 * avg('missRate')).toFixed(0)}% | ${avg('lift').toFixed(2)} | ${v[0].outcome.replace(/_/g, ' ')} |`);
}
if (!fr.length) p('| none stated | | | | |');
p('');
p('**"...and why did I also get hurt?"**');
p('');
p('| condition | lineages | hurt rate | lift | reads as |');
p('|---|---|---|---|---|');
const hr = Object.entries(hurtAgree).sort((a, b) => b[1].length - a[1].length || Math.abs(b[1][0].lift - 1) - Math.abs(a[1][0].lift - 1));
for (const [k, v] of hr.slice(0, 12)) {
  const avg = f => v.reduce((a, r) => a + r[f], 0) / v.length;
  p(`| \`${k}\` | ${v.length}/${NL} | ${(100 * avg('hurtRate')).toFixed(0)}% | ${avg('lift').toFixed(2)} | ${v[0].reads} |`);
}
if (!hr.length) p('| none stated | | | | |');
p('');

// ── Caveats ─────────────────────────────────────────────────────────────────
p('## What these findings are and are not');
p('');
p('- **"Strong for him," not "strong in general."** His tactics were written for melee, so a weapon he can\'t wield well (ranged especially) scores low because of him, not the weapon. The opponent table is the closer read on the weapon itself.');
p('- **One arena.** All fights were on The Circuit: walls at both edges, full-width floor, no hazards, and no pickups in the sim. Ring-out, hazard and terrain mechanics could not exist here, so he could not find them.');
p('- **Weapon and class are learned separately.** Specific combos can be stronger or weaker than the two parts suggest. Combo cells are recorded in the dumps but not used for his choice.');
p('- **The opponent is the game\'s AI, not a human.** A counter that beats the AI may not beat a person.');
p('- **The mechanics engine only watches his own swings,** so anything that never involves him attacking stays invisible to it.');
fs.writeFileSync(OUT, md);
console.log('wrote ' + path.relative(ROOT, OUT) + ` (${NL} lineages, ${totalMatches} matches)`);
