#!/usr/bin/env node
/**
 * Wraps the shipped brain checkpoint as a script so Sovereign can load it on file://,
 * where fetch() is blocked. smb-brain.js tries data/brain/latest.json first and falls
 * back to a <script> tag for data/brain/latest.js, which sets window.SOV_BRAIN_CKPT.
 *
 * Rerun after swapping latest.json, or the file:// copy keeps the old brain.
 * The package scripts (tools/package/build-*.sh) run it themselves.
 *
 * Usage: node tools/brain/ckpt-js.js [--in=data/brain/latest.json] [--out=data/brain/latest.js]
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const args = Object.fromEntries(process.argv.slice(2).map(a => {
  const m = a.match(/^--([^=]+)=(.*)$/);
  return m ? [m[1], m[2]] : [a.replace(/^--/, ''), true];
}));
const IN  = path.resolve(ROOT, args.in  || 'data/brain/latest.json');
const OUT = path.resolve(ROOT, args.out || 'data/brain/latest.js');

const ck = JSON.parse(fs.readFileSync(IN, 'utf8'));   // throws on a bad checkpoint
fs.writeFileSync(OUT, '// Generated by tools/brain/ckpt-js.js from latest.json. Do not edit.\n' +
                      'window.SOV_BRAIN_CKPT = ' + JSON.stringify(ck) + ';\n');
console.log(`[ckpt-js] iter ${ck.iter || '?'} -> ${path.relative(ROOT, OUT)} (${fs.statSync(OUT).size} bytes)`);
